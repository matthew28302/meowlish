
/**
 * Catalogue thú cưng — file này được CLIENT import (`PETS_CATALOG`), nên mọi
 * thứ ở đây đều bị đóng gói và gửi tới trình duyệt mọi khách.
 * TUYỆT ĐỐI không đặt dữ liệu cá nhân (email, tên thật, id người dùng) vào đây.
 * Xem `cinnamorollAccess.ts` cho phần kiểm tra quyền chỉ chạy ở server.
 */
export interface PetConfig {
  id: string;
  name: string;
  species: string;
  emoji: string;
  avatarBg: string;
  description: string;
  isSpecialVip?: boolean;
  /**
   * Đường dẫn tới tranh nhân vật 2D dạng "standee" (WebP bo góc alpha feather)
   * do pipeline `scripts/build-pet-art-2d.mjs` sinh ra, vd:
   * "/pet-art-2d/art2d_sanrio__hello_kitty.webp".
   * Chỉ là public asset path nên an toàn khi file này bị đóng gói xuống client.
   */
  sprite2d?: string;
  /** Nhãn hiển thị của franchise cho pet 2D, vd: "Sanrio", "Harry Potter". */
  art2dFranchise?: string;
  buff: {
    title: string;
    description: string;
    bonusType: 'exp' | 'listening' | 'streak' | 'writing' | 'speaking' | 'speed' | 'coins' | 'all';
    bonusPercent: number;
  };
  greetings: string[];
  eatSounds: string[];
  happyQuotes: string[];
}

