// Titles based on pet level
export function getPetTitle(level: number): string {
  if (level >= 30) return '👑 Thần Thú Bảo Hộ';
  if (level >= 20) return '🌟 Đại Sư Giao Tiếp';
  if (level >= 12) return '⚔️ Chiến Binh Ngữ Pháp';
  if (level >= 5) return '📖 Học Giả Tri Thức';
  return '🌱 Thú Cưng Tập Sự';
}
